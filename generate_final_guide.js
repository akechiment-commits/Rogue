import XLSX from 'xlsx';

const wb = XLSX.utils.book_new();

function addSheet(name, data) {
  const ws = XLSX.utils.aoa_to_sheet(data);
  ws['!cols'] = Array(15).fill(null).map(() => ({ wch: 20 }));
  XLSX.utils.book_append_sheet(wb, ws, name);
}

