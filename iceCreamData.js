export const ICE_CREAM_FLAVORS = Object.freeze(ICE_CREAM_FLAVORS_RAW.map((flavor) => ({
  ...flavor,
  name: ICE_CREAM_FLAVOR_NAME_RENAMES[flavor.name] || flavor.name,
})));

export function pickIceCreamFlavor(randomFn = Math.random) {
  if (ICE_CREAM_FLAVORS.length === 0) return null;
  const raw = Number(randomFn());
  const index = Math.min(ICE_CREAM_FLAVORS.length - 1, Math.max(0, Math.floor(raw * ICE_CREAM_FLAVORS.length)));
  return ICE_CREAM_FLAVORS[index];
}

/* 既存アイテムの祝呪・店・座標メタだけを残し、中身をアイスへ変換する。 */
export function convertToIceCream(item, randomFn = Math.random) {
  if (!item) return null;
  const flavor = pickIceCreamFlavor(randomFn);
  if (!flavor) return item;
  const keepKeys = [
    "id", "x", "y", "shopPrice", "_shopId", "_shopCharge", "_origCount",
    "blessed", "cursed", "bcKnown", "fullIdent", "discovered", "wallEmbedded",
  ];
  const preserved = Object.fromEntries(keepKeys.filter((key) => item[key] !== undefined).map((key) => [key, item[key]]));
  for (const key of Object.keys(item)) delete item[key];
  Object.assign(item, preserved, {
    name: flavor.name,
    type: "food",
    value: 15,
    desc: `${flavor.desc}\n${ICE_CREAM_EFFECT_DESCRIPTION}`,
    tile: 209,
    cooked: true,
    iceCream: true,
    iceCreamFlavor: flavor.name,
    _foodBase: flavor.name,
    sizeLabel: "普通の",
  });
  return item;
}
