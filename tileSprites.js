/*
 * Procedural 16×16 pixel-art tile generator.
 * Each tile defined as [palette[], data (256 hex-chars)].
 * Hex digit 0 = transparent, 1‑f → palette[i‑1].
 * Call generateTileImages() to get { [tileIndex]: HTMLCanvasElement }.
 */

const S = 16;

function mk(pal, data) {
  const c = document.createElement("canvas");
  c.width = S; c.height = S;
  const ctx = c.getContext("2d");
  for (let i = 0; i < S * S; i++) {
    const ci = parseInt(data[i], 16);
    if (ci === 0) continue;
    ctx.fillStyle = pal[ci - 1];
    ctx.fillRect(i % S, Math.floor(i / S), 1, 1);
  }
  return c;
}

